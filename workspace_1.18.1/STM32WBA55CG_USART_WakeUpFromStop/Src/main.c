/**
  * @brief Enter Stop 1 mode and handle wakeup.
  *        This function modularizes the Stop mode entry logic for clarity.
  * @retval None
  */
static void Enter_Stop_Mode(void)
{
  /* Insert 5 second delay before entering Stop mode */
 //HAL_Delay(5000);

  HAL_UART_Receive_DMA(&huart1, pRxBuff, 10);

  /* Enter STOP mode */
  HAL_PWR_EnterSTOPMode(PWR_LOWPOWERREGULATOR_ON, PWR_STOPENTRY_WFI);

  /* Reconfigure system clock after wake-up */
  SystemClock_Config();

  HAL_UART_Transmit_DMA(&huart1, pTxBuff, 10);

  /* After waking up, show message and received data */
  HAL_UART_Transmit(&huart1, (uint8_t*)UART_MSG_WAKEUP, sizeof(UART_MSG_WAKEUP)-1, HAL_MAX_DELAY);
  HAL_UART_Transmit(&huart1, (uint8_t*)UART_NEW_LINE, sizeof(UART_NEW_LINE)-1, HAL_MAX_DELAY);
}


