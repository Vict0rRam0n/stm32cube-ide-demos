static void MEMS_Init(void)
{
	  HTS221_IO_t io_ctx;
      uint8_t id;
      //LSM6DSO_AxesRaw_t axes;

      /* Link I2C functions to the  HTS221 driver */
      io_ctx.BusType     = HTS221_I2C_BUS;
      io_ctx.Address     = HTS221_I2C_ADDRESS;
      io_ctx.Init        = BSP_I2C1_Init;
      io_ctx.DeInit      = BSP_I2C1_DeInit;
      io_ctx.ReadReg     = BSP_I2C1_ReadReg;
      io_ctx.WriteReg    = BSP_I2C1_WriteReg;
      io_ctx.GetTick     = BSP_GetTick;

      HTS221_RegisterBusIO(&Sensor, &io_ctx);

      /* Read the  HTS221 WHO_AM_I register */
      HTS221_ReadID(&Sensor, &id);
      if (id != HTS221_ID) {
             Error_Handler();
      }
      /* Initialize the HTS221 temperature sensor */
      HTS221_Init(&Sensor);

      /* Configure the HTS221 temperature and humidity sensor */
      HTS221_GetCapabilities(&Sensor, &Cap);
      HTS221_HUM_SetOutputDataRate(&Sensor, 26.0f);
      HTS221_TEMP_SetOutputDataRate(&Sensor, 26.0f);

      /* Start the HTS221 sensor */
      HTS221_HUM_Enable(&Sensor);
      HTS221_TEMP_Enable(&Sensor);
}

