void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
  if (huart->Instance == USART1)
  {
    // Limit Size to TX buffer capacity
    if (Size > TX_BUF_SIZE)
    {
      Size = TX_BUF_SIZE;
    }

    // Simple echo: copy received data to TX buffer and send via DMA
    if ((Size > 0U) && (txBusy == 0U))
    {
      memcpy(txBuffer, rxBuffer, Size);

      txBusy = 1U;
      if (HAL_UART_Transmit_DMA(&huart1, txBuffer, Size) != HAL_OK)
      {
        // If something goes wrong, release the flag so we can try again
        txBusy = 0U;
      }
    }

    // Note:
    // - RX DMA remains enabled by HAL_UARTEx_ReceiveToIdle_DMA
    // - Incoming data continues to fill rxBuffer in circular mode
    Turn_Off_LEDs();

      if (memcmp(rxBuffer, txBuffer, Size) == 0)
      {
        // Match: turn LD1 ON, LD3 OFF
        HAL_GPIO_WritePin(LD2_GPIO_Port, LD2_Pin, GPIO_PIN_RESET);
      }
      else
      {
        // Mismatch: turn LD3 ON, LD1 OFF
        HAL_GPIO_WritePin(LD3_GPIO_Port, LD3_Pin, GPIO_PIN_RESET);
      }
  }
}

